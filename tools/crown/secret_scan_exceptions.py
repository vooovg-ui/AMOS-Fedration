#!/usr/bin/env python3
"""الهدف: سجلُّ الاستثناءاتِ المُعلَنةِ لماسحِ الأسرارِ في التاريخِ المنشورِ (W-064).

النطاق: أسطرُ تاريخٍ **مُضافةٌ** يقرأُها `verify_secret_boundaries.py` كتلةَ مفتاحٍ
خاصٍّ، وقد رُوجِعَت سطرًا سطرًا وثبتَ أنَّها ليست مادّةَ مفتاحٍ. ولا يُعفى مسارٌ
ولا مجلَّدٌ ولا نوعُ ملفٍّ هنا: الإعفاءُ **لبصمةِ نصِّ سطرٍ بعينِه** لا لموضعِه،
فلا يصيرُ «كونُه في اختبارٍ» بابًا يمرُّ منه سرٌّ حقيقيّ.

المالك: التاج
تاريخ الإنشاء: 2026-08-29
تاريخ آخر تعديل: 2026-08-29

لماذا سجلٌّ لا تخفيفُ نمطٍ
--------------------------
الحكمُ الأحمرُ على «main» كانَ سببُه سطرًا واحدًا في اختبارٍ سلبيٍّ يحملُ ترويسةَ
PEM مكتوبةً حرفًا (`DISC-024`). وأمامَ ذلك ثلاثةُ طرقٍ لا رابعَ:

1. **توسيعُ النمطِ أو استثناءُ `tests/`** — وهذا إضعافُ حرسٍ لأجلِ خُضرةٍ: ماسحٌ
   يتخطّى مجلَّدًا كاملًا يترك للسرِّ بابًا مفتوحًا باسمِ الاختبار. مرفوضٌ.
2. **إعادةُ كتابةِ التاريخِ** لمحوِ السطرِ من كلِّ التزامٍ — وهذا يُبطِلُ بصماتَ
   الالتزامِ المُقيَّدةَ في سجلِّ الإكمالِ وأرقامَ الدمجِ المنشورةَ، أي يُفسِدُ
   سلسلةَ الإثباتِ لإصلاحِ سطرٍ ليس سرًّا. مرفوضٌ.
3. **إعلانُ الاستثناءِ ببصمةٍ ومُراجَعةٍ وسببٍ** — فيبقى الحرسُ بكاملِ عضِّه على كلِّ
   ما لم يُراجَعْ، ويُقرأُ المُراجَعُ **مُعلَنًا** لا مسكوتًا عنه. وهذا المُختار.

وحدُّه مُعلَنٌ: الاستثناءُ لا يُطهِّرُ التاريخَ، بل يُعلِنُ أنَّ هذا النصَّ بعينِه
رُوجِعَ فلم يكنْ مادّةَ مفتاحٍ. ولو تغيَّرَ حرفٌ واحدٌ في السطرِ لصارَ بصمةً أخرى
غيرَ مُعفاةٍ.

ويحرُسُ السجلَّ نفسَه فحصانِ لا واحدٌ:
* استثناءٌ لم يبقَ له سطرٌ في التاريخِ = مخالفةٌ (`STALE_EXCEPTION`) — كي لا تتراكمَ
  إعفاءاتٌ ميتةٌ تُوسِّعُ الثقبَ بلا أن يُلاحظَها أحدٌ.
* سطرٌ مُضافٌ يحملُ كتلةَ مفتاحٍ ولا بصمةَ له هنا = مخالفةٌ كما كانَ قبلَ اليومِ.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass


@dataclass(frozen=True)
class HistoryException:
    """سطرُ تاريخٍ رُوجِعَ فثبتَ أنَّه ليس مادّةَ مفتاحٍ."""

    digest: str
    """بصمةُ `sha256` لنصِّ السطرِ بعدَ حذفِ علامةِ الإضافةِ وتشذيبِ الفراغِ."""

    first_seen_commit: str
    """أوّلُ التزامٍ أضافَ السطرَ — مُقيَّدٌ كي يُعادَ فحصُه بالعينِ متى لزمَ."""

    reviewed_on: str
    reviewer: str
    record: str
    """القيدُ والاكتشافُ الذي فيه تعليلُ المُراجَعةِ منشورًا."""

    reason: str


#: مُراجَعةُ 2026-08-29: سطرٌ واحدٌ في المستودعِ كلِّه، وهو قيمةُ اختبارٍ سلبيٍّ
#: تُمرَّرُ إلى `EffectPayload` لتُرفَض. ليس فيه جسمُ base64 ولا خاتمةُ `END`،
#: فليس مفتاحًا يُسرَّبُ بل نصٌّ يُشبِهُه قصدًا كي يُختبَرَ الرفضُ. وقد أُزيلَ
#: من شجرةِ العملِ في `W-064` بالتركيبِ، ويبقى في التاريخِ لأنَّ التاريخَ لا يُمحى.
DECLARED_HISTORY_LINES: tuple[HistoryException, ...] = (
    HistoryException(
        digest="08aaa7013291553a52b073cdaadb123d131fe7f19eb25c0f0c21a1620680b726",
        first_seen_commit="0111c95",
        reviewed_on="2026-08-29",
        reviewer="Driving H",
        record="DISC-024 · W-064",
        reason=(
            "قيمةُ اختبارٍ سلبيٍّ في «tests/sovereignty/test_outbox.py» تُمرَّرُ لتُرفَضَ: "
            "ترويسةٌ بلا جسمٍ ولا خاتمةٍ، لا مادّةَ مفتاحٍ ولا سرَّ يُدوَّرُ."
        ),
    ),
)


def line_digest(line: str) -> str:
    """بصمةُ سطرِ تاريخٍ كما يقرأُها الماسحُ: تُحذَفُ علامةُ الإضافةِ ويُشذَّبُ الفراغُ."""
    text = line[1:] if line.startswith("+") else line
    return hashlib.sha256(text.strip().encode("utf-8")).hexdigest()


def declared_digests() -> frozenset[str]:
    return frozenset(item.digest for item in DECLARED_HISTORY_LINES)


def classify(added_lines: list[str]) -> tuple[list[str], list[str]]:
    """يُقسِمُ الأسطرَ المُضافةَ إلى (غيرِ مُعلَنةٍ · مُعلَنةٍ مُراجَعةٍ).

    والقسمةُ ببصمةِ النصِّ وحدَها: لا مسارَ يُعفى ولا امتدادَ ولا مجلَّدَ اختباراتٍ.
    """
    declared = declared_digests()
    undeclared = [line for line in added_lines if line_digest(line) not in declared]
    accounted = [line for line in added_lines if line_digest(line) in declared]
    return undeclared, accounted


def stale_exceptions(added_lines: list[str]) -> list[HistoryException]:
    """استثناءٌ لا يقابلُه سطرٌ في التاريخِ: إعفاءٌ ميتٌ يُعلَنُ ولا يُترَكُ."""
    seen = {line_digest(line) for line in added_lines}
    return [item for item in DECLARED_HISTORY_LINES if item.digest not in seen]
