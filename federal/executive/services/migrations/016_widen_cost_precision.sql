-- الهدف: أن تُقيَّدَ كلفةُ نداءٍ أصغرُ من `0.00005$` بقيمتِها لا صفرًا، تنفيذًا
--        لحسمِ المالكِ في Q-42 · الشقِّ الثاني · الخيارِ (أ) — وذلكَ في أعمدةِ
--        الكلفةِ **وحدَها** دونَ سائرِ أعمدةِ المالِ.
-- النطاق: federal/executive/services/migrations
-- المالك: federal/executive/services
-- تاريخ الإنشاء: 2026-08-24 (W-036 · Q-42 (أ))
-- تعتمد على: 014_unify_money_representation.sql (هي التي جعلَت العمودَ NUMERIC(20,4))
-- =============================================================================
--
-- ## بأيِّ سلطةٍ يُعدَّلُ عمودُ مالٍ حُسِمَ نوعُه في Q-20
--
-- بنصِّ المالكِ في جلسةِ 2026-08-24 المُقيَّدِ في
-- `docs/audit/SOVEREIGN_DECISION_REGISTER.md` § «حسمُ المالكِ في Q-42» —
-- **الشقُّ الثاني · الخيارُ (أ)**: **«توسيعُ دقّةِ أعمدةِ الكلفةِ وحدَها»**.
--
-- وهذا **ليسَ نقضًا لحسمِ Q-20** ولا التفافًا عليه: Q-20 قضى أن يكونَ لكلِّ مبلغٍ
-- **تمثيلٌ واحدٌ مُعلَنٌ** لا أن يكونَ المقياسُ أربعًا إلى الأبدِ. والمقياسُ يبقى
-- واحدًا لكلِّ مبلغٍ في الدولةِ (`NUMERIC(20,4)`)، ويُفرَدُ **صنفُ الكلفةِ** بمقياسٍ
-- مُعلَنٍ في نفسِ ملفِّ العقدِ (`common/money.py` · `COST_SCALE`) لا في زاويةٍ.
-- ولو كانَ الحسمُ توسيعًا عامًّا لكانَ هجرةً على أربعةِ جداولَ لا على واحدٍ.
--
-- ## لماذا لزِمَت هجرةٌ ولم يكفِ تغييرُ النموذجِ في بايثون
--
-- لأنَّ `ModelBase.metadata.create_all` يُنشئُ الجدولَ **إن لم يكن موجودًا** ولا
-- يُعدِّلُ عمودًا قائمًا. فقاعدةُ الإنتاجِ التي مرَّت عليها الهجرةُ 014 كانت ستبقى
-- على `NUMERIC(20,4)` بينما النموذجُ يُرسِلُ ثمانَ منازلَ — فتُقرَّبَ القيمةُ في
-- القاعدةِ صامتةً، ويصيرُ العملُ **دعوى توسيعٍ لا توسيعًا**. والحرسُ في
-- `tests/test_w036_cost_precision_and_pricing_divergence.py` يُثبِتُ المقياسَ على
-- القاعدةِ نفسِها لا على النموذجِ وحدَه.
--
-- ## ماذا يُفقَدُ — وثمنٌ يُقالُ ولا يُخفى
--
-- 1. **لا صفٌّ يُفقَدُ ولا قيمةٌ تُقرَّبُ إلى أدنى.** التحويلُ من `(20,4)` إلى
--    `(20,8)` **توسيعٌ محضٌ** في المنازلِ العشريّةِ: كلُّ قيمةٍ قائمةٍ تُمثَّلُ
--    تمامًا (`0.0000` تصيرُ `0.00000000`)، فلا تقريبَ ولا اقتطاعَ ولا نسخةٌ
--    احتياطيّةٌ لازمةٌ لأجلِ التمثيلِ.
-- 2. **والحدُّ الأعلى يَضيقُ حقًّا: من 9×10¹¹ إلى 9×10⁷.** وهذا ليسَ اختيارًا بل
--    حسابًا: دقّةُ SQLite مضمونةٌ ما دامَ `MAX × 10^SCALE < 2⁵³`، فزيادةُ المقياسِ
--    أربعَ منازلَ تُنقِصُ الحدَّ أربعَ مراتبَ. فمن قرأَ هذه الهجرةَ «توسيعًا بلا
--    مقابلٍ» أخطأَ: هي **مقايضةُ مقدارٍ بدقّةٍ**، ومقبولةٌ بقياسٍ لأنَّ قيدَ كلفةِ
--    نداءٍ واحدٍ يتجاوزُ تسعينَ مليونَ دولارٍ ليسَ مالًا بل خطأً، ورفضُه في
--    القاعدةِ أولى من قبولِه.
-- 3. **ولا يُمَسُّ في هذه الهجرةِ أيُّ عمودِ مالٍ آخرَ**: لا
--    `state_case_claims.amount`، ولا `state_authority_grants.max_amount`، ولا
--    `state_government_delegations.max_amount`. وهي باقيةٌ على `NUMERIC(20,4)`
--    بحسمِ Q-20 — والحسمُ قالَ «أعمدةَ الكلفةِ وحدَها»، ومن وسَّعَ غيرَها وسَّعَ
--    ما لم يُؤذَنْ له فيه.
-- 4. **ولا تمسُّ `treasury_transactions` و`treasury_reports`** — وهي
--    `double precision` وحدةُ قياسٍ تشغيليّةٌ (Q-17) مقيَّدةٌ سؤالًا مستقلًّا
--    (Q-28)، وليست كلفةً بالدولارِ.
--
-- ## أثرٌ يُقالُ ولا يُوارى
--
-- الصفوفُ القديمةُ التي قُيِّدَت صفرًا وهي ليست صفرًا **لا تُصحَّحُ بهذه الهجرةِ**:
-- المعلومةُ ضاعَت عندَ الكتابةِ لا عندَ التخزينِ، ولا يُخترَعُ لها بديلٌ. فالهجرةُ
-- تُصلِحُ **ما يُقيَّدُ من الآنَ** وتُعلِنُ أنَّ ما مضى ناقصٌ بمقدارِ ما دونَ
-- `0.00005$` لكلِّ نداءٍ — وهو نقصٌ مُعلَنٌ في السجلِّ لا مكتومٌ.
-- =============================================================================

BEGIN;

-- === 1 · كلفةُ نداءِ النموذج: NUMERIC(20,4) → NUMERIC(20,8) ==================
-- توسيعُ منازلَ محضٌ. و`USING` غيرُ لازمٍ لأنَّ التحويلَ ضِمنيٌّ وبلا فقدٍ،
-- لكنَّه يُكتَبُ صريحًا كي تُقرأَ نيّةُ الكاتبِ في الهجرةِ لا تُستنتَجَ.
ALTER TABLE IF EXISTS model_cost_log
    ALTER COLUMN cost_usd TYPE NUMERIC(20,8)
    USING cost_usd::NUMERIC(20,8);

ALTER TABLE IF EXISTS model_cost_log
    ALTER COLUMN cost_usd SET DEFAULT 0;

-- === 2 · القيدُ يُبدَّلُ لأنَّ حدَّه تغيَّرَ لا لأنَّه ضاقَ اعتباطًا ==========
-- القيدُ الذي وضعَته الهجرةُ 014 يسمحُ حتى 9×10¹¹، وهو **غيرُ صحيحٍ بعدَ الآنَ**:
-- بمقياسِ ثمانٍ يتجاوزُ ذلك حدَّ التمثيلِ الدقيقِ على SQLite. فيُحذَفُ القيدُ
-- القديمُ ويوضَعُ الحدُّ المشتقُّ (9×10⁷). و`IF EXISTS` لأنَّ قاعدةً أُنشِئَت من
-- النموذجِ (لا من الهجراتِ) لا تحملُ القيدَ باسمِه.
ALTER TABLE IF EXISTS model_cost_log
    DROP CONSTRAINT IF EXISTS ck_model_cost_log_cost_usd;

ALTER TABLE IF EXISTS model_cost_log
    ADD CONSTRAINT ck_model_cost_log_cost_usd CHECK (
        cost_usd >= 0 AND cost_usd <= 90000000
    );

COMMIT;
