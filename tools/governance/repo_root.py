"""
مُكتشِفُ جذرِ المستودعِ — بعلامةٍ تُثبِتُه، لا بعُمقٍ مكتوبٍ يُخمِّنُه
الهدف: إعطاءُ كلِّ أداةٍ وفحصٍ جذرًا **مُثبَتًا بعلامةٍ في الشجرةِ**، فلا يصيرُ محلُّ القياسِ مجلَّدًا آخرَ صامتًا إذا نُقِلَ ملفٌّ أو أُعيدَ تنظيمُ المجلَّداتِ (`DISC-041` · سببُ `DISC-032` الأعمقُ).
النطاق: tooling-gates (`WI-032`)
المالك: tools/governance/
تاريخ الإنشاء: 2026-09-02
تاريخ آخر تعديل: 2026-09-02

العَطبُ المُعالَجُ:
    `REPO_ROOT = Path(__file__).resolve().parents[2]` يعُدُّ مجلَّداتٍ صاعدةً بعددٍ
    مكتوبٍ. فإن نُقِلَ الملفُّ درجةً واحدةً صارَ «الجذرُ» مجلَّدًا آخرَ **بلا خطأٍ**:
    البوّابةُ تُشغَّلُ، وتقرأُ شجرةً غيرَ التي يُظَنُّ أنَّها تُقرأُ، وتُخرِجُ رمزَ صفرٍ.

القاعدةُ هنا — مُعلَنةٌ لا مطويّةٌ:
    الجذرُ **يُثبَتُ بعلامةٍ**: صعودٌ من موضعِ الطالبِ حتّى أوّلِ مجلَّدٍ تجتمعُ فيه
    علاماتُ هذا المستودعِ. وإن لم توجدْ علامةٌ حتّى الجذرِ الأعلى **يُرفَعُ خطأٌ
    يُسمّي الموضعَ** — ولا يُهبَطُ إلى تخمينٍ ولا يُرجَعُ مسارٌ «معقولٌ»، فالهبوطُ
    الصامتُ هو عينُ العَطبِ المُعالَجِ.

حدُّ الأداةِ — مُعلَنٌ لا مطويٌّ:
    - العلامتانِ مِلفّانِ في الجذرِ؛ فشجرةٌ مؤقَّتةٌ تُقلِّدُهما تُقرأُ جذرًا — وهذا
      **مقصودٌ**: الفحوصُ تبني شجرًا مُقلِّدةً عمدًا، والحكمُ يجبُ أن يقعَ عليها.
    - ولا تُقرأُ `.git` علامةً: مرآةٌ ضحلةٌ أو نسخةٌ بلا `.git` جذرٌ صحيحٌ كذلك.
"""

from __future__ import annotations

from pathlib import Path

#: علاماتٌ لا تجتمعُ إلّا في جذرِ هذا المستودعِ.
ROOT_MARKERS: tuple[str, ...] = (
    "PROJECT_STATE.md",
    "docs/governance/work/THE_ROADMAP.md",
)


class RepositoryRootNotFound(RuntimeError):
    """لم تُوجَدْ علامةُ جذرٍ — يُرفَعُ ولا يُبتلَعُ."""


def is_repository_root(candidate: Path) -> bool:
    """أمُجتمِعةٌ علاماتُ الجذرِ في هذا المجلَّدِ؟"""
    return all((candidate / marker).exists() for marker in ROOT_MARKERS)


def discover_repo_root(start: str | Path) -> Path:
    """يصعدُ من `start` حتّى أوّلِ جذرٍ مُعلَّمٍ، أو يرفعُ خطأً يُسمّي الموضعَ."""
    origin = Path(start).resolve()
    for candidate in (origin, *origin.parents):
        if candidate.is_dir() and is_repository_root(candidate):
            return candidate
    raise RepositoryRootNotFound(
        f"لم تُوجَدْ علامةُ جذرٍ ({' · '.join(ROOT_MARKERS)}) صعودًا من {origin} — "
        "ولا يُخمَّنُ جذرٌ: قياسٌ على شجرةٍ غيرِ مقصودةٍ يُخرِجُ أخضرَ كاذبًا"
    )
