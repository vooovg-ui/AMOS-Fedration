"""
بطاقةُ هويّةِ أثرِ التشغيل — Runtime State Identity Card

الهدف: تنفيذُ حسمِ المالكِ في Q-40 (الخيارُ ج): كلُّ ملفِّ حالةِ تشغيلٍ يُولَّدُ
       على القرصِ يحملُ ترويسةَ هدفٍ في مضمونِه نفسِه، ويُنشَأُ `README.md` معَ
       المجلَّدِ الذي يُولَّدُ فيه — **بلا تضييقِ كاشفٍ وبلا نقلِ موضعِ سجلٍّ**.
النطاق: كتّابُ حالةِ التشغيلِ في `core/sovereignty` (سجلُّ الذرّيّةِ · سجلُّ
        الأذونِ المُستهلَكةِ · سجلُّ الصادرِ · سجلُّ التعويضِ)، ولا يمسُّ هذا
        الملفُّ كاشفَ الهويّةِ ولا مواضعَ السجلّاتِ.
المالك: core/sovereignty — النواةُ السياديّة
تاريخ الإنشاء: 2026-08-24
بأيِّ سلطةٍ: حسمُ المالكِ في 2026-08-23 على Q-40 «(ج) بطاقةُ هويّةٍ للأثرِ
             نفسِه» — مُقيَّدٌ في `docs/audit/SOVEREIGN_DECISION_REGISTER.md`،
             ويُنفَّذُ في العملِ `W-034`.

**لماذا مفتاحٌ في المضمونِ لا ملفٌّ مجاورٌ.** نصُّ الحسمِ يقولُ «يُكتَبُ **في كلِّ
ملفِّ** حالةِ تشغيلٍ مولَّدٍ ترويسةُ هدفٍ». وملفُّ حالةِ التشغيلِ هنا JSON، فترويسةُ
هدفِه مفتاحٌ في أعلاه لا تعليقٌ (JSON لا يعرفُ التعليقاتِ)، والمفتاحُ المُختارُ
`$comment` هو ما يقبلُه كاشفُ الهويّةِ أصلًا لملفّاتِ JSON — فلا يُضيَّقُ الكاشفُ
ولا يُوسَّعُ ليقبلَ ما لم يكن يقبلُه.

**وثمنُ ذلك مُعلَنٌ ومحروسٌ:** المفتاحُ المُضافُ يقعُ في خريطةِ سجلّاتٍ مفاتيحُها
معرّفاتُ عملياتٍ أو أذونٍ، فلو قُرِئَ كما هو لصارَ «سجلًّا» وهميًّا يزيدُ العدَّ
ويكسرُ القراءةَ. فكلُّ قارئٍ يُجرِّدُه بـ`strip_identity` قبلَ الاستعمالِ،
ويحرسُ ذلك اختبارٌ يُثبِتُ أنَّ العدَّ والسجلّاتَ لا تتغيّرُ بالوسمِ.

**وما لا تفعلُه هذه الوحدةُ:** لا تكتبُ `README` فوقَ واحدٍ موجودٍ (فلا تمسُّ
بطاقةَ هويّةٍ كتبَها إنسانٌ)، ولا تُنشئُ مجلَّدًا (المُنشِئُ هو الكاتبُ)، ولا
تبتلعُ خطأً: فشلُ كتابةِ البطاقةِ يُبلَّغُ ولا يُسقِطُ كتابةَ السجلِّ — لأنَّ
سجلَّ الذرّيّةِ عقدُ سلامةٍ، ومنعُ كتابتِه لأجلِ بطاقةٍ يقلبُ الأولويّاتِ.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Any, Mapping

#: مفتاحُ ترويسةِ الهدفِ داخلَ ملفِّ JSON — من علاماتِ الهدفِ التي يقبلُها
#: `tools/governance/check_repository_identity.py` أصلًا.
IDENTITY_KEY = "$comment"

#: مفاتيحُ ترويسةٍ تُجرَّدُ عندَ القراءةِ. أُبقيَ الجمعُ لأنَّ ملفّاتٍ قديمةً
#: قد تحملُ `$schema` كُتِبَ بيدٍ، فلا يُقرأُ سجلًّا أيضًا.
IDENTITY_KEYS = frozenset({IDENTITY_KEY, "$schema", "$id"})


@dataclass(frozen=True)
class RuntimeStateCard:
    """تعريفُ أثرِ تشغيلٍ: مَن كتبَه ولماذا وبأيِّ سلطةٍ — يُعلَنُ لا يُستنتَجُ."""

    name: str
    purpose: str
    scope: str
    owner: str
    authority: str

    def comment(self) -> str:
        """نصُّ ترويسةِ الهدفِ كما يُكتَبُ في الملفِّ نفسِه."""
        return (
            f"الهدف: {self.purpose} | "
            f"النطاق: {self.scope} | "
            f"المالك: {self.owner} | "
            f"بأيِّ سلطةٍ: {self.authority} | "
            "هذا الملفُّ أثرُ تشغيلٍ مولَّدٌ آليًّا: لا يُحرَّرُ بيدٍ، ولا يُقيَّدُ "
            "في المستودعِ، وحذفُه يُفقِدُ حالةَ تشغيلٍ فلا يُحذَفُ لتخضيرِ بوّابةٍ."
        )

    def readme(self, *, today: date | None = None) -> str:
        """بطاقةُ هويّةِ المجلَّدِ بحقولِ المادةِ التاسعةِ مملوءةً لا شكليّةً."""
        stamp = (today or date.today()).isoformat()
        return (
            f"# {self.name}\n\n"
            "## التعريف\n\n"
            f"{self.purpose}\n\n"
            "## النطاق\n\n"
            f"{self.scope}\n\n"
            "## المالك\n\n"
            f"{self.owner}\n\n"
            "## تاريخ الإنشاء\n\n"
            f"{stamp} — أُنشِئَت هذه البطاقةُ آليًّا عندَ أوّلِ كتابةِ أثرِ تشغيلٍ "
            "في هذا المجلَّد.\n\n"
            "## تاريخ آخر تعديل\n\n"
            f"{stamp}\n\n"
            "## المحتويات\n\n"
            "ملفّاتُ حالةِ تشغيلٍ مولَّدةٌ آليًّا، يحملُ كلُّ واحدٍ منها ترويسةَ "
            f"هدفٍ في مفتاحِ `{IDENTITY_KEY}` في أعلاه. المجلَّدُ **مُستثنًى من "
            "الدفعِ** فلا يدخلُ المستودعَ منه شيءٌ، والبطاقةُ حاضرةٌ على القرصِ "
            "ليجدَ كاشفُ الهويّةِ هويّةَ ما يزنُه.\n\n"
            "## بأيِّ سلطةٍ\n\n"
            f"{self.authority}\n"
        )


def stamped(payload: Mapping[str, Any], *, card: RuntimeStateCard) -> dict[str, Any]:
    """أعِدْ الحِملَ موسومًا بترويسةِ هدفِه — ولا تُبدِّلْ حِملَ المُنادي.

    الوسمُ يُكتَبُ ولا يُقرَأُ سجلًّا: `sort_keys=True` عندَ الكتابةِ يجعلُ
    `$comment` أوّلَ المفاتيحِ (‏`$` أدنى من الأرقامِ والحروفِ)، فتقعُ الترويسةُ
    في نافذةِ القراءةِ التي يفحصُها كاشفُ الهويّةِ.
    """
    out: dict[str, Any] = {IDENTITY_KEY: card.comment()}
    out.update(payload)
    return out


def strip_identity(raw: Mapping[str, Any]) -> dict[str, Any]:
    """اقرأِ السجلّاتِ وحدَها: ترويسةُ الهدفِ ليست سجلًّا فلا تُعَدُّ ولا تُقرَأ."""
    return {k: v for k, v in raw.items() if k not in IDENTITY_KEYS}


def ensure_directory_card(directory: Path, *, card: RuntimeStateCard) -> Path | None:
    """اكتبْ `README.md` معَ المجلَّدِ إن لم يكن فيه واحدٌ. لا تُكتَبُ فوقَ موجودٍ.

    يُرجَعُ مسارُ البطاقةِ إن كُتِبَت، و`None` إن كانت موجودةً أو تعذّرَت
    الكتابةُ. وتعذّرُ الكتابةِ يُبلَّغُ على `stderr` ولا يُسقِطُ كتابةَ السجلِّ:
    سلامةُ سجلِّ الذرّيّةِ مقدَّمةٌ على بطاقةٍ توضيحيّة.
    """
    readme = directory / "README.md"
    if readme.exists():
        return None
    try:
        readme.write_text(card.readme(), encoding="utf-8")
    except OSError as exc:  # يُبلَّغُ ولا يُبتلَع (القاعدة 16)
        print(
            f"  [تنبيه] تعذّرَت كتابةُ بطاقةِ هويّةِ «{readme}» ({exc}) — "
            "السجلُّ يُكتَبُ، والبطاقةُ ناقصةٌ فتُسقِطُ بوّابةَ الهويّةِ إن كانَ "
            "المجلَّدُ داخلَ شجرةِ العملِ.",
            file=sys.stderr,
        )
        return None
    return readme


